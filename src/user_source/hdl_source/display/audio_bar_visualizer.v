`timescale 1ns/1ps
// 10/29 audio SPECTRUM bars for the hall screen (expansion requirement 5: spectrum energy by a
// self-made DFT, drawn as RGB bars over the video before HDMI). Replaces the 10/28 loudness bars;
// same ports, same place (right half of the old waveform box), same SW2 / enable rules.
//
// 16 bars, 12 px wide with a 4 px gap, in BAR_X..BAR_X+255 x BAR_Y..BAR_Y+63. Bar k is the energy
// of the music around F[k] (60 Hz on the left .. 12 kHz on the right, log spaced), 1 px = 0.5 dB,
// 61 px = 30 dB. Bit-exact reference: verification/ui3/spectrum_model.py (header has the maths).
//
// DFT engine: 16 Goertzel filters (one DFT bin per band), time-shared - one band after the other
// for every PCM tap (48 kHz, ~520 pixel clocks apart; 5 clocks a band). Band k uses blocks of 2^M[k]
// taps (2048 for 60 Hz .. 32 for 12 kHz: each bin is about a third of its centre frequency wide)
// with a 32-step Hann window; the blocks of the bands are staggered so at most one band ends a block
// on any tap. The two Goertzel states of each band live in a block RAM (32 x 27); the coefficients
// 2cos w, sin w and the window are in a block ROM (spectrum_rom.mif, made by gen_tables.py). At the
// end of a block the bin is (re, im); its magnitude is taken in the log domain: la, lb = 8 log2 |re|,
// |im| (the same register is shifted left until its top two bits differ, 1 bit a clock), L = max +
// G(|la - lb|) (log of sqrt(re^2 + im^2)), height = 1.5 L - OFF[k] clamped to 0..61; the band's
// pending value keeps the frame maximum. The sample is read from pcm_tap_left while the tap is
// worked on (pcm_tap_cdc holds it until the next tap).
// Frame rule (everything visible changes only here, so a frame never tears): at a frame start,
// once the engine is idle, each bar = max(pending, bar - BAR_FALL) and pending = 0; then every cap
// rises to its bar or, on every CAP_FALL-th frame, falls by 1 px. If enable was low at the frame
// start, bars / caps / pending are cleared instead. The frame is visible when show (SW2) and enable
// were both 1 at its start. While enable is low the taps are ignored (the block counter and states
// just wait). A band's two states are written 0 at its block end, so the next block starts from 0.
module audio_bar_visualizer #(
    parameter integer BAR_X = 320, BAR_Y = 252, BARS = 16, BAR_W = 12, BAR_PITCH = 16, BAR_H = 64,
    parameter integer CAP_FALL = 3,               // frames per 1 px of cap fall
    parameter integer BAR_FALL = 2,               // px per frame a bar sinks
    parameter [23:0] BAR_COLOR = 24'h0e6e6e, CAP_COLOR = 24'hf08c00,
    parameter ROM_INIT = "spectrum_rom.mif", ROM_HEX = "spectrum_rom.hex"
)(
    input wire clk, rst_n, vsync, de,
    input wire [23:0] rgb_in,
    input wire [9:0] pixel_x,
    input wire show,                              // SW2 up
    input wire enable, pcm_tap_valid,
    input wire signed [15:0] pcm_tap_left,
    output wire [23:0] rgb_out
);
    localparam integer W = 27;
    // ---------------- band tables (generated by gen_tables.py from spectrum_model.py) ----------------
    reg [3:0] k;                    // band in work
    reg [2:0] t_m;                  // log2 block length - 5 (0..6)
    reg [8:0] t_off;                // 1.5 x full-scale level - FS_PX - TILT
    always @* begin
        case (k)
            // TABLE_BEGIN
            4'd0: begin t_m = 3'd6; t_off = 9'd138; end
            4'd1: begin t_m = 3'd6; t_off = 9'd138; end
            4'd2: begin t_m = 3'd5; t_off = 9'd126; end
            4'd3: begin t_m = 3'd5; t_off = 9'd126; end
            4'd4: begin t_m = 3'd4; t_off = 9'd114; end
            4'd5: begin t_m = 3'd4; t_off = 9'd114; end
            4'd6: begin t_m = 3'd3; t_off = 9'd102; end
            4'd7: begin t_m = 3'd3; t_off = 9'd102; end
            4'd8: begin t_m = 3'd2; t_off = 9'd90; end
            4'd9: begin t_m = 3'd2; t_off = 9'd90; end
            4'd10: begin t_m = 3'd1; t_off = 9'd78; end
            4'd11: begin t_m = 3'd1; t_off = 9'd78; end
            4'd12: begin t_m = 3'd0; t_off = 9'd62; end
            4'd13: begin t_m = 3'd0; t_off = 9'd58; end
            4'd14: begin t_m = 3'd0; t_off = 9'd54; end
            4'd15: begin t_m = 3'd0; t_off = 9'd50; end
            // TABLE_END
            default: begin t_m = 3'd0; t_off = 9'd0; end
        endcase
    end
    reg [2:0] g;
    reg [7:0] gd;
    always @* begin
        case (gd)
            // G_BEGIN
            8'd0: g = 3'd4;
            8'd1: g = 3'd4;
            8'd2: g = 3'd3;
            8'd3: g = 3'd3;
            8'd4: g = 3'd2;
            8'd5: g = 3'd2;
            8'd6: g = 3'd2;
            8'd7: g = 3'd2;
            8'd8: g = 3'd1;
            8'd9: g = 3'd1;
            8'd10: g = 3'd1;
            8'd11: g = 3'd1;
            8'd12: g = 3'd1;
            8'd13: g = 3'd1;
            // G_END
            default: g = 3'd0;
        endcase
    end

    // ---------------- frame / raster ----------------
    reg vs_q, de_q;
    wire frame_start = vs_q && !vsync;
    reg [8:0] line_y;

    // ---------------- ROM: 0..15 2cos w, 16..31 sin w (x 2^16), 32..63 Hann window ----------------
    reg [5:0] rom_a;
    wire [17:0] rom_q;
    ui_table_rom #(.WIDTH(18), .WORDS(64), .AW(6), .INIT(ROM_INIT), .HEX(ROM_HEX)) u_rom(
        .clk(clk), .addr(rom_a), .q(rom_q));

    // ---------------- state RAM: address {band, 0} = s1, {band, 1} = s2 ----------------
    reg [4:0] ram_a;
    reg ram_we;
    reg signed [W-1:0] ram_d;
    wire signed [W-1:0] ram_q;
`ifdef SPECTRUM_BEHAVIORAL_RAM
    reg signed [W-1:0] ram [0:31];
    reg signed [W-1:0] ram_q1;
    integer r;
    initial for (r = 0; r < 32; r = r + 1) ram[r] = 0;      // block RAM powers up as 0 (no INIT_FILE)
    always @(posedge clk) begin
        if (ram_we) ram[ram_a] <= ram_d;
        ram_q1 <= ram[ram_a];
    end
    assign ram_q = ram_q1;
`else
    EG_LOGIC_BRAM #(
        .DATA_WIDTH_A(W), .DATA_WIDTH_B(W), .ADDR_WIDTH_A(5), .ADDR_WIDTH_B(5),
        .DATA_DEPTH_A(32), .DATA_DEPTH_B(32), .MODE("SP"),
        .REGMODE_A("NOREG"), .REGMODE_B("NOREG"), .WRITEMODE_A("NORMAL"), .WRITEMODE_B("NORMAL"),
        .RESETMODE("SYNC"), .IMPLEMENT("9K")
    ) u_state(
        .dia(ram_d), .addra(ram_a), .cea(1'b1), .ocea(1'b0), .clka(clk), .wea(ram_we), .rsta(1'b0),
        .bea(1'b0), .doa(ram_q),
        .dib({W{1'b0}}), .addrb(5'd0), .ceb(1'b0), .oceb(1'b0), .clkb(1'b0), .web(1'b0), .rstb(1'b0),
        .beb(1'b0), .dob());
`endif

    // ---------------- engine ----------------
    localparam [2:0] E_IDLE = 3'd0, E_RD = 3'd1, E_S1 = 3'd2, E_S2 = 3'd3, E_CALC = 3'd4, E_WR2 = 3'd5,
                     E_LOG = 3'd6, E_CMB = 3'd7;
    reg [2:0] st;
    reg tap_pend;
    reg [10:0] cnt;                 // taps worked on since reset, counted when a tap starts
    reg signed [W-1:0] s1r, t;
    reg signed [10:0] xw;
    reg pass;                       // log normaliser: 0 = re, 1 = im
    reg [4:0] e;
    reg [7:0] la;
    wire [10:0] sft = cnt + {6'd0, k, 1'b0};             // stagger: band k is 2k + 1 taps ahead
    wire [10:0] mask = ~(11'h7ff << ({1'b0, t_m} + 4'd5));
    wire [10:0] n = sft & mask;
    wire last = n == mask;
    wire [4:0] widx = n >> t_m;
    wire signed [9:0] x = pcm_tap_left[15:6];
    wire signed [18:0] xh = x * $signed({1'b0, rom_q[7:0]});
    wire signed [W-1:0] dv = xw - ram_q;                // ram_q = s2                  // xw sign-extends
    wire signed [W+17:0] prod = $signed(rom_q) * s1r;  // rom_q: 2cos w in CALC, sin w from WR2 on
    wire signed [W-1:0] p16 = prod[W+15:16], p17 = prod[W+16:17];
    wire found = t[W-1] ^ t[W-2];
    wire norm_done = found || e == 5'd0;
    wire [7:0] lz = {e, t[W-3:W-5] ^ {3{t[W-1]}}};
    wire [7:0] lmax = la > lz ? la : lz;
    always @* gd = la > lz ? la - lz : lz - la;
    wire [8:0] lsum = lmax + g;
    wire [9:0] v15 = lsum + (lsum >> 1);
    wire [9:0] vh = v15 > t_off ? v15 - t_off : 10'd0;
    wire [5:0] val = vh > 10'd61 ? 6'd61 : vh[5:0];

    // ---------------- bars: pending / bar / cap, 16 x 6 LUT RAMs ----------------
    reg [5:0] pend_mem [0:BARS-1];
    reg [5:0] lv_mem [0:BARS-1];
    reg [5:0] cap_mem [0:BARS-1];
    reg sweep_req, sweep, clr, fall_now, vis;
    reg [3:0] sk;
    reg [1:0] fall_n;
    wire [9:0] rx = pixel_x - BAR_X;
    wire [3:0] pos = sweep ? sk : rx[7:4];
    wire [5:0] h = lv_mem[pos];
    wire [5:0] c = cap_mem[pos];
    wire [5:0] pv = pend_mem[sweep ? sk : k];
    wire [5:0] sunk = h > BAR_FALL ? h - BAR_FALL : 6'd0;
    wire [5:0] nl = clr ? 6'd0 : pv > sunk ? pv : sunk;
    wire eng_start = st == E_IDLE && tap_pend && enable && !sweep_req && !sweep;
    always @(posedge clk) begin
        if (sweep) begin
            pend_mem[sk] <= 6'd0;
            lv_mem[sk] <= nl;
            if (clr) cap_mem[sk] <= 6'd0;
            else if (nl >= c) cap_mem[sk] <= nl;
            else if (fall_now) cap_mem[sk] <= c - 1'b1;
        end else if (st == E_CMB && val > pv) pend_mem[k] <= val;
    end

    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            vs_q <= 1; de_q <= 0; line_y <= 0;
            tap_pend <= 0; cnt <= 0;
            st <= E_IDLE; k <= 0; s1r <= 0; t <= 0; xw <= 0; pass <= 0; e <= 0; la <= 0;
            rom_a <= 0; ram_a <= 0; ram_we <= 0; ram_d <= 0;
            sweep_req <= 0; sweep <= 0; clr <= 1; fall_now <= 0; fall_n <= 0; vis <= 0; sk <= 0;
        end else begin
            vs_q <= vsync; de_q <= de;
            if (!vsync) line_y <= 0;
            else if (de_q && !de) line_y <= line_y + 1'b1;
            // frame start: latch the frame's controls, sweep once the engine is idle
            if (frame_start) begin
                sweep_req <= 1'b1; clr <= !enable; vis <= show && enable;
                fall_now <= fall_n == 0;
                fall_n <= fall_n == CAP_FALL - 1 ? 2'd0 : fall_n + 1'b1;
            end else if (sweep_req && st == E_IDLE && !sweep) begin
                sweep_req <= 1'b0; sweep <= 1'b1; sk <= 0;
            end
            if (sweep) begin
                sk <= sk + 1'b1;
                if (sk == BARS - 1) sweep <= 1'b0;
            end
            // taps
            if (!enable) tap_pend <= 1'b0;
            else if (pcm_tap_valid) tap_pend <= 1'b1;
            else if (eng_start) tap_pend <= 1'b0;
            if (eng_start) cnt <= cnt + 1'b1;
            // engine, per band: RD (addresses) -> S1 -> S2 (s1, window) -> CALC (write s0) -> WR2 (write
            // s1) [-> LOG re -> LOG im -> CMB at a block end] -> next band
            ram_we <= 1'b0;
            case (st)
                E_IDLE: if (eng_start) begin k <= 0; st <= E_RD; end
                E_RD: begin ram_a <= {k, 1'b0}; rom_a <= {1'b1, widx}; st <= E_S1; end
                E_S1: begin ram_a <= {k, 1'b1}; rom_a <= {2'b00, k}; st <= E_S2; end
                E_S2: begin
                    s1r <= ram_q; xw <= xh[18:8];
                    rom_a <= {2'b01, k}; st <= E_CALC;
                end
                E_CALC: begin
                    ram_we <= 1'b1; ram_a <= {k, 1'b0}; ram_d <= last ? {W{1'b0}} : dv + p16;
                    t <= dv + p17; st <= E_WR2;
                end
                E_WR2: begin
                    ram_we <= 1'b1; ram_a <= {k, 1'b1}; ram_d <= last ? {W{1'b0}} : s1r;
                    if (last) begin e <= W - 2; pass <= 1'b0; st <= E_LOG; end
                    else if (k == BARS - 1) st <= E_IDLE;
                    else begin k <= k + 1'b1; st <= E_RD; end
                end
                E_LOG: begin
                    if (!norm_done) begin
                        t <= {t[W-1], t[W-3:0], t[W-1]}; e <= e - 1'b1;
                    end else if (!pass) begin
                        la <= lz; t <= p16; e <= W - 2; pass <= 1'b1;
                    end else st <= E_CMB;
                end
                default: begin      // E_CMB: pending max written above; next band
                    if (k == BARS - 1) st <= E_IDLE;
                    else begin k <= k + 1'b1; st <= E_RD; end
                end
            endcase
        end
    end

    // ---------------- drawing ----------------
    wire [8:0] ry = line_y - BAR_Y;
    wire in_box = vis && de && pixel_x >= BAR_X && pixel_x < BAR_X + BARS * BAR_PITCH &&
                  line_y >= BAR_Y && line_y < BAR_Y + BAR_H;
    wire in_bar_x = rx[3:0] < BAR_W;
    wire [5:0] up = BAR_H - 1 - ry[5:0];          // height above the bottom, 0..63
    wire bar_px = in_box && in_bar_x && up < h;
    wire cap_px = in_box && in_bar_x && c != 0 && (up == c + 1 || up == c + 2);
    assign rgb_out = cap_px ? CAP_COLOR : bar_px ? BAR_COLOR : rgb_in;
    // synthesis translate_off
    integer i;
    initial for (i = 0; i < BARS; i = i + 1) begin pend_mem[i] = 0; lv_mem[i] = 0; cap_mem[i] = 0; end
    initial if (BAR_PITCH != 16 || BARS != 16 || BAR_H != 64) $fatal(1, "bar geometry is fixed (16 x 16 px, 64 px high)");
    // synthesis translate_on
endmodule
